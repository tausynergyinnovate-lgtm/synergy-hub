// Generates src/app/palette.css: every Tailwind hue the hub uses, as CSS variables with
// light values (Tailwind defaults) and dark values tuned for contrast on dark surfaces.
// Run: node scripts/gen-palette.mjs
import colors from 'tailwindcss/colors.js';
import { writeFileSync } from 'node:fs';

const HUES = ['indigo', 'red', 'emerald', 'amber', 'blue', 'sky', 'violet', 'pink', 'orange'];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900];
const hex2 = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const ch = (rgb) => rgb.map((x) => Math.round(x)).join(' ');
const mix = (a, b, t) => a.map((x, i) => x * t + b[i] * (1 - t));
const BASE = hex2('#1c1c1e');

// Apple-style neutral grays (systemGray family) replacing Tailwind "stone"
const GRAY_LIGHT = { 50: '#f7f7f9', 100: '#f0f0f3', 200: '#e3e3e8', 300: '#c7c7cc', 400: '#6e6e73', 500: '#636366', 600: '#48484a', 700: '#3a3a3c', 800: '#2c2c2e', 900: '#1c1c1e' };
const GRAY_DARK = { 50: '#232326', 100: '#2c2c2f', 200: '#3a3a3d', 300: '#545458', 400: '#98989f', 500: '#a1a1a8', 600: '#c7c7cc', 700: '#d8d8dd', 800: '#e8e8ed', 900: '#f5f5f7' };
const GRAY_HC_LIGHT = { 300: '#a1a1a6', 400: '#4a4a4f', 500: '#444448', 200: '#c7c7cc' };
const GRAY_HC_DARK = { 300: '#8e8e93', 400: '#c2c2c8', 500: '#cacad0', 200: '#5a5a5e' };

const light = [], dark = [], hcL = [], hcD = [];
for (const s of SHADES) { light.push(`--stone-${s}: ${ch(hex2(GRAY_LIGHT[s]))};`); dark.push(`--stone-${s}: ${ch(hex2(GRAY_DARK[s]))};`); }
for (const [s, v] of Object.entries(GRAY_HC_LIGHT)) hcL.push(`--stone-${s}: ${ch(hex2(v))};`);
for (const [s, v] of Object.entries(GRAY_HC_DARK)) hcD.push(`--stone-${s}: ${ch(hex2(v))};`);
for (const h of HUES) {
  const c = (s) => hex2(colors[h][s]);
  for (const s of SHADES) light.push(`--${h}-${s}: ${ch(c(s))};`);
  const d = { 50: mix(c(500), BASE, 0.16), 100: mix(c(500), BASE, 0.24), 200: mix(c(500), BASE, 0.36), 300: mix(c(500), BASE, 0.55),
    400: c(400), 500: c(400), 600: c(400), 700: c(300), 800: c(200), 900: c(100) };
  for (const s of SHADES) dark.push(`--${h}-${s}: ${ch(d[s])};`);
}
const css = `/* generated by scripts/gen-palette.mjs — do not edit by hand */
:root {\n  ${light.join('\n  ')}\n}
@media (prefers-color-scheme: dark) {\n  :root {\n    ${dark.join('\n    ')}\n  }\n}
@media (prefers-contrast: more) {\n  :root {\n    ${hcL.join('\n    ')}\n  }\n}
@media (prefers-contrast: more) and (prefers-color-scheme: dark) {\n  :root {\n    ${hcD.join('\n    ')}\n  }\n}
`;
writeFileSync(new URL('../src/app/palette.css', import.meta.url), css);
console.log('palette.css written', light.length, 'vars');
